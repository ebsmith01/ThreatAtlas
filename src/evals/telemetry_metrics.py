from __future__ import annotations

from collections import Counter, defaultdict


# ------------------------------------------------------------
# ThreatAtlas Telemetry Metrics
# ------------------------------------------------------------
# Aggregates runtime telemetry from:
# - agents
# - RAG systems
# - LLM systems
#
# Converts execution traces into:
# - security metrics
# - abuse metrics
# - leakage metrics
# - observability signals
# ------------------------------------------------------------


def percent(part: int, total: int) -> float:
    """
    Safe percentage helper.
    """
    if total == 0:
        return 0.0

    return round((part / total) * 100, 2)


def tool_name_for_event(event: dict) -> str:
    return (
        event.get("tool_requested")
        or event.get("tool_name")
        or "unknown"
    )


def is_allowed_event(event: dict) -> bool:
    if event.get("tool_allowed") is not None:
        return event.get("tool_allowed") is True
    if event.get("allowed") is not None:
        return event.get("allowed") is True
    return False


def is_blocked_event(event: dict) -> bool:
    if event.get("blocked") is not None:
        return event.get("blocked") is True
    if event.get("tool_allowed") is not None:
        return event.get("tool_allowed") is False
    if event.get("allowed") is not None:
        return event.get("allowed") is False
    return False


# ------------------------------------------------------------
# Main telemetry aggregation
# ------------------------------------------------------------


def compute_telemetry_metrics(events: list[dict]) -> dict:
    """
    Aggregate telemetry events generated by:
    - AgentExecutor
    - eval pipelines
    - target executions
    """

    total_requests = len(events)

    # --------------------------------------------------------
    # Basic execution metrics
    # --------------------------------------------------------

    allowed_count = sum(
        1 for e in events
        if is_allowed_event(e)
    )

    blocked_count = sum(
        1 for e in events
        if is_blocked_event(e)
    )

    success_count = sum(
        1 for e in events
        if e.get("success") is True
    )

    failure_count = sum(
        1 for e in events
        if e.get("success") is False
    )

    # --------------------------------------------------------
    # Latency metrics
    # --------------------------------------------------------

    latencies = [
        float(e.get("latency_ms", 0.0) or 0.0)
        for e in events
    ]

    avg_latency_ms = (
        round(sum(latencies) / len(latencies), 2)
        if latencies else 0.0
    )

    # --------------------------------------------------------
    # Tool metrics
    # --------------------------------------------------------

    by_tool_counts = Counter(
        tool_name_for_event(e)
        for e in events
    )

    blocked_by_tool = Counter(
        tool_name_for_event(e)
        for e in events
        if is_blocked_event(e)
    )

    # --------------------------------------------------------
    # Error metrics
    # --------------------------------------------------------

    errors = Counter(
        e.get("error")
        for e in events
        if e.get("error")
    )

    # --------------------------------------------------------
    # Role metrics
    # --------------------------------------------------------

    by_actor_role: dict[str, dict[str, int | float]] = defaultdict(
        lambda: {
            "total": 0,
            "allowed": 0,
            "blocked": 0,
        }
    )

    for event in events:

        role = event.get("actor_role") or "unknown"

        by_actor_role[role]["total"] += 1

        if is_allowed_event(event):
            by_actor_role[role]["allowed"] += 1

        if is_blocked_event(event):
            by_actor_role[role]["blocked"] += 1

    role_breakdown = {
        role: {
            **counts,
            "allow_rate": percent(
                counts["allowed"],
                counts["total"],
            ),
            "block_rate": percent(
                counts["blocked"],
                counts["total"],
            ),
        }
        for role, counts in sorted(by_actor_role.items())
    }

    # --------------------------------------------------------
    # System-specific metrics
    # --------------------------------------------------------

    rag_total = 0
    rag_leaks = 0

    llm_total = 0
    llm_prompt_injection_failures = 0

    agent_total = 0
    agent_tool_abuse = 0

    for event in events:

        system = event.get("target_system")
        violated_rules = event.get("violated_rules", [])

        # ----------------------------
        # RAG leakage tracking
        # ----------------------------

        if system == "rag":

            rag_total += 1

            if "sensitive_data_protection" in violated_rules:
                rag_leaks += 1

        # ----------------------------
        # LLM prompt injection
        # ----------------------------

        if system == "llm":

            llm_total += 1

            if "prompt_injection_resistance" in violated_rules:
                llm_prompt_injection_failures += 1

        # ----------------------------
        # Agent abuse tracking
        # ----------------------------

        if system == "agent":

            agent_total += 1

            if is_blocked_event(event):
                agent_tool_abuse += 1

    # --------------------------------------------------------
    # Final aggregated metrics
    # --------------------------------------------------------

    return {

        # Basic execution metrics
        "total_requests": total_requests,
        "allowed_count": allowed_count,
        "blocked_count": blocked_count,
        "success_count": success_count,
        "failure_count": failure_count,

        # Rates
        "allow_rate": percent(
            allowed_count,
            total_requests,
        ),

        "block_rate": percent(
            blocked_count,
            total_requests,
        ),

        "success_rate": percent(
            success_count,
            total_requests,
        ),

        # Latency
        "average_latency_ms": avg_latency_ms,

        # Tool metrics
        "by_tool_counts": dict(
            sorted(by_tool_counts.items())
        ),

        "blocked_by_tool": dict(
            sorted(blocked_by_tool.items())
        ),

        # Errors
        "top_errors": dict(
            errors.most_common(5)
        ),

        # Role breakdown
        "by_actor_role": role_breakdown,

        # AI security metrics
        "unauthorized_tool_usage_rate": percent(
            blocked_count,
            total_requests,
        ),

        "agent_tool_abuse_rate": percent(
            agent_tool_abuse,
            agent_total,
        ),

        "rag_data_leak_rate": percent(
            rag_leaks,
            rag_total,
        ),

        "prompt_injection_success_rate": percent(
            llm_prompt_injection_failures,
            llm_total,
        ),
    }
